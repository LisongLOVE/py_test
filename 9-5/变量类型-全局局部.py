# ==================== 变量作用域:全局变量 vs 局部变量（讲解 + 可视化版） ====================
# 【两个概念】
# 局部变量: 在【函数内部】定义的变量 → 只在函数内有效,出了函数就消失
# 全局变量: 在【函数外部】定义的变量 → 整个文件都能用
#
# 【三条核心规则】
# 1. 函数【内】可以直接【读取】全局变量
# 2. 函数【内】想【修改】全局变量(数字/字符串/元组等不可变类型),必须先 global 声明
#    不声明直接赋值 → Python 认为你在新建一个【同名局部变量】,全局变量根本没变
# 3. 列表/字典等【可变类型】在函数内【原地修改】(append、改元素)不需要 global
#    因为没有产生新对象,改的是原数据本身


# ---------- 例1: 局部变量——函数外访问不到 ----------
# 【讲解】
# 函数里定义的变量是"临时工":函数运行时存在,运行完就销毁
# 在函数外直接用它 → 报错 NameError
def demo1():
    x = 10              # 局部变量,只属于 demo1
    print(f"  函数内部: x = {x}  (能用)")

print("=== 例1: 局部变量出了函数就没了 ===")
demo1()
print("操作: 函数外访问 x")
try:
    print(x)
except NameError as e:
    print(f"结果: 报错! NameError: {e}")


# ---------- 例2: 全局变量——函数内可以直接读取 ----------
# 【讲解】
# 函数外定义的 name,函数内不声明也能直接用(只读不写)
name = "张三"            # 全局变量
def demo2():
    print(f"  函数内部读到: name = {name}")

print("\n=== 例2: 函数内读取全局变量 ===")
print(f"原始: 函数外 name = {name!r}")
print("操作: demo2() 内部直接读 name")
demo2()


# ---------- 例3: 函数内"修改"全局变量,不写 global 会失败 ----------
# 【讲解】这是最容易踩的坑!
# count = count + 1 时,Python 看到函数内有赋值,就把 count 当局部变量
# 但右边又要读 count 的旧值 → 局部变量还没赋值就被读 → UnboundLocalError
count = 0               # 全局变量
def demo3():
    count = 100         # ⚠️ 这不是修改全局!是新建了一个同名局部变量
    print(f"  函数内部的 count = {count}  (局部的)")

print("\n=== 例3: 不写 global,赋值只会造局部变量 ===")
print(f"原始: 全局 count = {count}")
demo3()
print(f"结果: 函数外全局 count 还是 = {count}  ← 没变!函数里改的是局部变量")


# ---------- 例4: global 声明——真正修改全局变量 ----------
# 【讲解】
# global count 告诉 Python:"这个 count 用外面的那个,别新建"
count2 = 0
def demo4():
    global count2       # 声明:count2 是全局的
    count2 = 100        # 这次改的是真的全局变量
    print(f"  函数内部: count2 = {count2}")

print("\n=== 例4: 写了 global,才能真正改全局 ===")
print(f"原始: 全局 count2 = {count2}")
demo4()
print(f"结果: 函数外全局 count2 = {count2}  ← 真的变了!")


# ---------- 例5: 可变类型(列表)原地修改,不需要 global ----------
# 【讲解】
# lst.append() 没有"赋值"动作(没有 =),只是在原对象上修改
# 函数内函数外用的是同一个列表(引用) → 不需要 global 也能改
lst = [1, 2, 3]         # 全局列表
def demo5():
    lst.append(99)      # 原地修改,不是 lst = 新列表

print("\n=== 例5: 列表原地修改不用 global ===")
print(f"原始: 全局 lst = {lst}")
demo5()
print(f"结果: 全局 lst = {lst}  ← 变了!append 不需要 global")


# ---------- 例6: 同名变量——局部优先(遮蔽) ----------
# 【讲解】
# 函数内外有同名变量时,函数内默认用局部的(局部"遮住"了全局)
color = "红色"          # 全局
def demo6():
    color = "蓝色"      # 局部,和全局同名
    print(f"  函数内部: color = {color}  (用的局部)")

print("\n=== 例6: 同名时局部优先 ===")
print(f"原始: 全局 color = {color!r}")
demo6()
print(f"结果: 全局 color = {color!r}  (全局不受影响)")


# ---------- 小抄 ----------
# 场景                      |  函数内能直接用吗 |  怎么改全局
# -------------------------|----------------|------------------
# 读取全局变量              |  ✅ 直接读       |  -
# 修改数字/字符串(不可变)   |  ❌ 赋值=造局部  |  先 global x 再赋值
# 列表.append/字典加键(可变)|  ✅ 原地改即可   |  不需要 global
# 函数内定义的变量          |  仅函数内有效    |  外面访问报 NameError
# 内外同名                  |  函数内用局部的  |  global 可强制用全局
