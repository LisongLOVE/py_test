# ==================== 变量类型—可变不可变（讲解 + 可视化版） ====================
# 【分类】
# 可变类型  : 列表 list、字典 dict、集合 set     → 数据可以原地修改,地址不变
# 不可变类型: 数字 int/float、字符串 str、元组 tuple → 数据不能改,"改"=造新的+改指向
#
# 【判断方法】
# 修改数据后看 id(): 地址没变 → 可变;地址变了 → 不可变


# ---------- 例1: 可变类型——原地修改,地址不变 ----------
# 【讲解】
# 列表的 append/修改元素 都是在原数据上动手脚
# 数据没搬家 → id(地址)不变 → 这就是"可变"
print("=== 例1: 列表可变(改数据,地址不变) ===")
lst = [1, 2, 3]
print(f"原始: lst = {lst}, 地址 = {id(lst)}")
lst.append(4)                       # 原地添加
print(f"操作: lst.append(4)")
print(f"结果: lst = {lst}, 地址 = {id(lst)}  ← 地址相同,数据原地变")


# ---------- 例2: 不可变类型——"修改"必是新对象,地址必变 ----------
# 【讲解】
# 数字、字符串不允许原地修改
# 所谓"修改"实际是: 新造一个数据 + 变量改指向 → 地址变了 → 这就是"不可变"
print("\n=== 例2: 字符串不可变(改'数据',地址必变) ===")
s = "abc"
print(f"原始: s = {s!r}, 地址 = {id(s)}")
s = s + "d"                         # 新造"abcd",s改指向
print(f"操作: s = s + 'd'")
print(f"结果: s = {s!r}, 地址 = {id(s)}  ← 地址不同,是新对象")


# ---------- 例3: 数字同样不可变 ----------
print("\n=== 例3: 数字不可变 ===")
n = 100
print(f"原始: n = {n}, 地址 = {id(n)}")
n = n + 1                           # 新造101,n改指向
print(f"操作: n = n + 1")
print(f"结果: n = {n}, 地址 = {id(n)}  ← 地址不同,是新对象")


# ---------- 例4: 元组——彻底不可变,改一个元素直接报错 ----------
# 【讲解】
# 元组的元素根本不允许赋值,直接 TypeError
print("\n=== 例4: 元组不可变(改元素直接报错) ===")
t = (1, 2, 3)
print(f"原始: t = {t}")
print("操作: t[0] = 99")
try:
    t[0] = 99
except TypeError as e:
    print(f"结果: 报错! TypeError: {e}")
print("结论: 元组从语法上就禁止修改")


# ---------- 例5: 为什么要区分?——共享陷阱只在可变类型出现 ----------
# 【讲解】
# x2 = x1 传的是引用(同一份数据)
# 可变类型: 改x2 → 数据本身变了 → x1 跟着变 ⚠️
# 不可变类型: "改"x2 → x2改指向新数据 → x1 不受影响 ✅
print("\n=== 例5: 可变 vs 不可变 的共享差异 ===")
# ---- 可变类型：列表 ----
list1 = [1, 2, 3]
list2 = list1
print(f"[列表] list1 = {list1}, list2 = {list2}")
print(f"  list1 地址 = {id(list1)}")
print(f"  list2 地址 = {id(list2)}  ← 相同! 指向同一块内存")
list2.append(99)
print(f"操作: list2.append(99)")
print(f"  list1 地址 = {id(list1)}, 值 = {list1}  ← 跟着变了!(同一份数据)，换句话说，改2,1也会变")
print(f"  list2 地址 = {id(list2)}, 值 = {list2}  ← 地址没变,原地改的")

# ---- 不可变类型：字符串 ----
print()
s1 = "abc"
s2 = s1
print(f"[字符串] s1 = {s1!r}, s2 = {s2!r}")
print(f"  s1 地址 = {id(s1)}")
print(f"  s2 地址 = {id(s2)}  ← 相同! 指向同一个字符串")
s2 = s2 + "!"
print(f"操作: s2 = s2 + '!'")
print(f"  s1 地址 = {id(s1)}, 值 = {s1!r}  ← 没变!")
print(f"  s2 地址 = {id(s2)}, 值 = {s2!r}  ← 地址变了! s2改指向新对象")


# ---------- 小抄 ----------
# 类型        |  可变?  |  修改后id变吗 |  x2=x1后改x2,x1变吗
# -----------|--------|--------------|-------------------
# 列表 list   |  ✅可变 |  不变(原地改) |  ⚠️ 变(同一份数据)
# 字典 dict   |  ✅可变 |  不变(原地改) |  ⚠️ 变(同一份数据)
# 集合 set    |  ✅可变 |  不变(原地改) |  ⚠️ 变(同一份数据)
# 数字 int    |  ❌不可变|  变(造新对象) |  ❌ 不变
# 字符串 str  |  ❌不可变|  变(造新对象) |  ❌ 不变
# 元组 tuple  |  ❌不可变|  变(造新对象) |  ❌ 不变(且改元素直接报错)
