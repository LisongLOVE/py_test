# ==================== 变量地址指向数据（讲解 + 可视化版） ====================
# 【核心概念】
# 变量不是"装数据的盒子",而是"指向数据的标签"(专业说法:引用 reference)
#
#   数据(对象)  →  真实存在内存里,有唯一的内存地址(像仓库门牌号)
#   变量        →  一个名字,里面存的是数据的"内存地址"(像贴在货物上的便利贴)
#
# 用 id(变量) 可以查看变量指向的内存地址
# 判断两个变量是否指向同一个数据: id(a) == id(b) 或 a is b


# ---------- 例1: 一个数据,可以贴多个标签 ----------
# 【讲解】
# b = a 执行时,不会复制数据!只是让 b 也指向 a 指向的那份数据
print("=== 例1: 一个数据,多个标签 ===")
a = 10
b = a                       # b 不复制 10,只是也指向 10
print(f"原始: a = 10, b = a")
print(f"结果: id(a) = {id(a)}, id(b) = {id(b)}")
print(f"结论: 两个地址{'相同' if id(a) == id(b) else '不同'} → 同一份数据,两个标签")


# ---------- 例2: 重新赋值 = 把标签撕下来,贴到新数据上 ----------
# 【讲解】
# a = 20 不会修改原来的 10!而是新造一个 20,让 a 改指向 20
# 原来 b 还贴在 10 上,所以 b 不受影响
print("\n=== 例2: 重新赋值只改变'指向',不影响别的标签 ===")
a = 20                      # a 改指向新数据 20
print("操作: a = 20")
print(f"结果: a = {a}(指向新数据), b = {b}(还指向原来的10)")
print(f"验证: id(a) = {id(a)}, id(b) = {id(b)} → 地址不同了,a已改指向")


# ---------- 例3: 可变对象(列表)——多个标签共享同一份数据 ----------
# 【讲解】
# list2 = list1 同样不复制!两个标签指向【同一个列表】
# 危险点: 通过任何一个标签修改列表,另一个标签看的数据也"变了"
# (数据只有一份,变的不是指向,而是数据本身)
print("\n=== 例3: 列表的共享陷阱 ===")
list1 = [1, 2, 3]
list2 = list1               # 两个标签指向同一个列表
print(f"原始: list1 = {list1}, list2 = {list2}")
print(f"验证: id(list1) = {id(list1)}, id(list2) = {id(list2)} → 同一个列表")
list2[0] = 99               # 通过 list2 修改数据
print(f"操作: list2[0] = 99  (通过list2修改)")
print(f"结果: list1 = {list1}  ← list1 也'变'了!")
print(f"真相: 数据只有一份,list1/list2 都指着它,数据本身被改了")


# ---------- 例4: 不可变对象(字符串/数字)——没有共享陷阱 ----------
# 【讲解】
# 字符串、数字、元组是不可变的:无法原地修改
# s2 = s2 + "!" 的真实过程: 新造一个字符串 "hello!",让 s2 改指向它
# 所以 s1 不会受影响
print("\n=== 例4: 字符串没有共享陷阱 ===")
s1 = "hello"
s2 = s1                     # 两个标签指向同一个字符串
s2 = s2 + "!"               # 不是修改原数据!是新造"hello!",s2 改指向
print(f"原始: s1 = 'hello', s2 = s1")
print(f"操作: s2 = s2 + '!'   (新造数据,s2改指向)")
print(f"结果: s1 = {s1!r}  ← s1 不受影响")
print(f"      s2 = {s2!r}")
print(f"真相: 字符串不可改,'修改'都是'造新的+改指向'")


# ---------- 小抄 ----------
# 操作             |  实际发生的事                    |  影响别的标签吗
# ----------------|---------------------------------|----------------
# b = a           |  b 指向 a 指向的数据(不复制)      |  -（只是多了标签）
# a = 新值        |  a 撕标签贴到新数据上             |  ❌ 不影响
# 可变对象x[0]=99  |  数据本身被修改(指向没变)         |  ⚠️ 所有标签都看到新数据
# 不可变对象"修改" |  造新数据 + 该标签改指向          |  ❌ 不影响
