# ==================== 字符串 split() 方法（可视化对比版） ====================
# 每个例子都按：原始 → 操作 → 结果 展示
# 语法: str.split(sep=None, maxsplit=-1)
#   sep:      分隔符，默认 None（按任意空白字符分割：空格、\n、\t、\r）
#   maxsplit: 最大分割次数，默认 -1（不限次数）；设为 n 最多分割 n 次（返回 n+1 个元素）
# 返回值: 分割完成后的【列表】（分隔符本身不会出现在结果里）


# ------------------------------
# 示例1：指定单字符分隔符
print("=== 示例1: 按逗号分割 ===")
s = "a,b,c"
print(f"原始: {s!r}")
print("操作: s.split(',')  按逗号拆分")
print(f"结果: {s.split(',')}")

# ------------------------------
# 示例2：默认分隔符（无参数，按任意空白分割）
print("\n=== 示例2: 默认按空白分割 ===")
s = "hello   world\tworld2\nworld3"
print(f"原始: {s!r}")
print("操作: s.split()  不传参数，按空格/\\t/\\n 分割")
print(f"结果: {s.split()}")

# ------------------------------
# 示例3：多字符组合分隔符
print("\n=== 示例3: 多字符分隔符 ===")
s = "a#$b#$c#$d"
print(f"原始: {s!r}")
print("操作: s.split('#$')  用两个字符'#$'作为分隔符")
print(f"结果: {s.split('#$')}")

# ------------------------------
# 示例4：限制分割次数 maxsplit
print("\n=== 示例4: 限制分割次数 ===")
s = "a,b,c,d,e"
print(f"原始: {s!r}")
print("操作: s.split(',', 2)  最多分割2次 → 返回3个元素")
print(f"结果: {s.split(',', 2)}")
print("提示: 剩下没分割的部分保留在最后一个元素里")

# ------------------------------
# 示例5：分隔符不存在于原字符串
print("\n=== 示例5: 分隔符不存在 ===")
s = "hello"
print(f"原始: {s!r}")
print("操作: s.split('world')  'world'在s里不存在")
print(f"结果: {s.split('world')}（返回原字符串组成的单元素列表）")

# ------------------------------
# 注意事项：空字符串不能当分隔符
print("\n=== 注意: 空分隔符会报错 ===")
print("原始: 'abc'")
print('操作: "abc".split("")  ⚠️ 会抛 ValueError')
# print("abc".split(""))  # ValueError: empty separator
print("结果: ValueError: empty separator（取消注释可看到报错）")


# ---------- 小抄：一眼对照表 ----------
# 用法                  |  结果                |  说明
# ---------------------|---------------------|------------------
# "a,b".split(",")     |  ['a', 'b']         |  按逗号分
# "a b".split()        |  ['a', 'b']         |  按任意空白分
# "a#$b".split("#$")   |  ['a', 'b']         |  多字符分隔符
# "a,b,c".split(",",1) |  ['a', 'b,c']       |  最多分1次
# "hello".split("x")   |  ['hello']          |  分隔符不存在→原样返回
