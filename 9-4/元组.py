# 元组，不可变的序列，不能修改元素
# 定义方式
info = ("张三", 18, "男")
print(f"原始: info = ('张三', 18, '男')  圆括号定义")
print(f"结果: 类型 = {type(info).__name__}")

info1 = "hello"
print(f"\n原始: info1 = 'hello'  没有逗号，只是字符串")
print(f"结果: 类型 = {type(info1).__name__}")

info2 = 1,2,3
print(f"\n原始: info2 = 1,2,3  不写括号，只有逗号")
print(f"结果: {info2}, 类型 = {type(info2).__name__}（逗号才是元组标志）")

info3 = "hello",
print(f"\n原始: info3 = 'hello',  单元素 + 逗号")
print(f"结果: {info3}, 类型 = {type(info3).__name__}（单元素元组必须带逗号）")

# 查询
print(f"\n原始: info = {info}")
print("操作: info[0]  取下标0")
print(f"结果: {info[0]}")
print("操作: info1[0]  字符串也能用下标")
print(f"结果: {info1[0]}")
print("操作: info2[2]  取下标2")
print(f"结果: {info2[2]}")
print("操作: info3[0]")
print(f"结果: {info3[0]}")

# 互换——》元组解包实现互换
a, b = 10, 20
print(f"\n原始: a, b = 10, 20  →  a = {a}, b = {b}")
print("操作: a, b = b, a  （右边先用旧值打包 (20, 10)，再解包）")
a, b = b, a
print(f"结果: a = {a}, b = {b}")

# =============================================
#                元组 vs 列表 的区别
# =============================================
# 一句话总结：列表【可变】，元组【不可变】
# ---------------------------------------------
# 【核心对比表】
# | 对比项       | 列表 list                                  | 元组 tuple                                      |
# |--------------|--------------------------------------------|------------------------------------------------|
# | 定义符号     | 方括号 `[1, 2, 3]`；单元素直接写 `[1]`     | 圆括号 `(1, 2, 3)`；单元素**必须加逗号** `(1,)` |
# | 能否修改     | ✅ 支持 `lst[0] = 99` 直接修改元素          | ❌ 不支持！修改直接抛 TypeError                 |
# | 常用方法     | 丰富：append / remove / pop / sort / ...   | 仅2个：count(统计次数)、index(查找位置)         |
# | 下标/切片    | ✅ `lst[0]`、`lst[1:3]` 正常用             | ✅ 完全支持，写法一致                           |
# | 遍历方式     | ✅ for 循环 / 推导式                       | ✅ 完全支持，写法一致                           |
# | 内存/速度    | 占用较大、速度较慢                         | 占用更小、速度更快                              |
# | 适用场景     | 数据会【增删改】（购物车、待办清单）        | 数据【固定不变】（坐标、颜色值、配置参数）      |
# ---------------------------------------------
# 【关键细节补充】
# 1. 核心差异——可变性（必记）
#    列表修改示例：
#       lst = [1, 2, 3]
#       lst[0] = 99   # ✅ 成功 → [99, 2, 3]
#    元组修改示例：
#       tup = (1, 2, 3)
#       tup[0] = 99   # ❌ 报错！TypeError: 'tuple' object does not support item assignment
#
# 2. 单元素定义的**致命坑**（重点对比列表&元组！）
#    ✅ 列表单元素：直接写，无需额外符号
#       list_single = ["hello"]   # 没问题，就是列表
#    ❌ 元组单元素：**必须加逗号**，否则会变成其他类型！
#       tup_wrong = ("hello")      # 不是元组！是带括号的字符串
#       tup_right = ("hello",)     # ✅ 正确，加逗号才是元组
#       tup_right2 = "hello",      # ✅ 也行，逗号才是元组的本质标志（括号可省略）
#
# 3. 共同特性（可将元组理解为【只读版的列表】）
#    下标访问、切片、for遍历、len()统计长度、in判断元素是否存在，用法完全一致
# ---------------------------------------------
# 【选型指南】
# → 数据需要**增删改**（比如动态更新的集合） → 选 列表
# → 数据**固定不变**（不希望被误改，提高代码安全性） → 选 元组
# =============================================
