# ==================== 序列类型通用操作（讲解 + 可视化版） ====================
# 【什么是序列类型】
# 序列 = "排成一排"的数据结构,Python 中最常用的是三种:
#   字符串 str : "abcde"   （字符的序列,不可变）
#   列表 list  : [1,2,3]   （元素的序列,可变）
#   元组 tuple : (1,2,3)   （元素的序列,不可变）
# 【本文件讲什么】
# 这三种序列有很多操作写法完全一样 → 叫"通用操作"
# 每个知识点 = 文字讲解 + 可视化示例（原始→操作→结果）

str1 = "abcde"               # 字符串
list1 = [1, 2, 3, 4, 5]      # 列表
tup1 = (10, 20, 30, 40, 50)  # 元组


# ============================== 1. 下标（索引）取值 ==============================
# 【讲解】
# 序列中每个元素都有自己的编号,叫"下标"(索引)
# 语法: x[下标]
# 规则:
#   正着数 → 从 0 开始: 第1个是0,第2个是1...
#   倒着数 → 从 -1 开始: 最后1个是-1,倒数第2个是-2...
# 注意: 下标越界(超出范围)会报 IndexError
print("\n=== 1. 下标取值 ===")
print(f"原始: str1 = {str1!r}, list1 = {list1}, tup1 = {tup1}")
print("操作: x[0]    取第1个")
print(f"结果: 字符串 → {str1[0]}, 列表 → {list1[0]}, 元组 → {tup1[0]}")
print("操作: x[-1]   取最后1个")
print(f"结果: 字符串 → {str1[-1]}, 列表 → {list1[-1]}, 元组 → {tup1[-1]}")


# ============================== 2. 切片 ==============================
# 【讲解】
# 切片 = 从序列中"截取一段",得到一个新序列(原序列不变)
# 语法: x[起始:结束:步长]
# 规则:
#   含头不含尾 → 包含起始下标,不包含结束下标
#   起始/结束/步长 都可以省略
#   步长默认为 1;步长为 2 表示隔1个取1个;
# 步长为2可以理解成list=【a,b,c,d,e】,第一个取a时，第二个取[a+2个下标]，list[0],list[0+2]---->a,c
# 步长为 -1 表示反向 → 反转整个序列，
# 注意: 切片不会修改原序列(字符串、元组本来也不许改)
print("\n=== 2. 切片 x[起:止:步长] ===")
print(f"原始: list1 = {list1}")
print("操作: x[1:4]    下标1取到3（含头不含尾）")
print(f"结果: {list1[1:4]}")
print("操作: x[::2]    省略起止,步长2 → 隔1个取1个")
print(f"结果: {list1[::2]}")
print("操作: x[::-1]   步长-1 → 反转")
print(f"结果: {list1[::-1]}")
print("三种序列切片写法一样:")
print(f"  字符串 {str1[::-1]}, 列表 {list1[::-1]}, 元组 {tup1[::-1]}")


# ============================== 3. 拼接 + 和重复 * ==============================
# 【讲解】
# +  : 把两个【同类型】序列拼成一个新序列
# *  : 把序列重复 n 次
# 注意:
#   只能同类型拼接 → 字符串+字符串 ✅,字符串+列表 ❌(报 TypeError)
#   + 和 * 都会生成新序列,不会修改原来的
print("\n=== 3. 拼接 + / 重复 * ===")
print("操作: 'ab' + 'cd'   → " + repr("ab" + "cd"))  #repr() = 把对象转成“带原样格式的字符串”，专门用来显示程序的“真实内容”。
print("操作: [1,2] + [3,4] → " + repr([1, 2] + [3, 4]))  #repr() = 把对象转成“带原样格式的字符串”，专门用来显示程序的“真实内容”。
print("操作: (1,2) + (3,4) → " + repr((1, 2) + (3, 4))) 
print("操作: 'ab' * 2      → " + repr("ab" * 2))
print("操作: [0] * 3       → " + repr([0] * 3))
print("⚠️ 注意: 只能同类型拼,不能字符串拼列表")


# ============================== 4. 成员判断 in / not in ==============================
# 【讲解】
# in      : 判断元素是否在序列里,在 → True,不在 → False
# not in  : 判断是否不在,不在 → True
# 返回值是布尔值 True / False,经常和 if 搭配使用
print("\n=== 4. 成员判断 in / not in ===")
print(f"原始: str1 = {str1!r}, list1 = {list1}, tup1 = {tup1}")
print("检查: 'a' in str1")
print(f"结果: {'a' in str1}")
print("检查: 3 in list1")
print(f"结果: {3 in list1}")
print("检查: 99 in tup1")
print(f"结果: {99 in tup1}")
print("检查: 99 not in tup1")
print(f"结果: {99 not in tup1}")


# ============================== 5. 长度 len() ==============================
# 【讲解】
# len() 是内置函数,统计序列里有几个元素
# 字符串的"元素"就是字符,所以 len("abc") = 3
print("\n=== 5. 长度 len() ===")
print("操作: len(x)")
print(f"结果: 字符串 → {len(str1)}, 列表 → {len(list1)}, 元组 → {len(tup1)}")


# ============================== 6. 最值 max / min / 求和 sum ==============================
# 【讲解】
# max(x) : 取最大值      min(x) : 取最小值
# sum(x) : 所有元素求和（只能用于数字序列!）
# 注意:
#   数字序列 → 按数值大小比
#   字符串序列 → 按字典序(编码)比,如 'b' > 'a'
#   混了不可比较的类型会报 TypeError
print("\n=== 6. 最值 max / min / 求和 sum ===")
print(f"原始: list1 = {list1}")
print("操作: max(x) / min(x) / sum(x)")
print(f"结果: 最大 → {max(list1)}, 最小 → {min(list1)}, 求和 → {sum(list1)}")


# ============================== 7. 遍历 for ==============================
# 【讲解】
# 遍历 = 把序列里的元素从头到尾逐个取出,挨个处理
# 语法: for 变量 in 序列:
#           循环体
# 每循环一次,变量就拿到当前这个元素
print("\n=== 7. 遍历 ===")
print(f"原始: tup1 = {tup1}")
print("操作: for x in tup1")
for x in tup1:
    print(f"  结果: {x}")


# ============================== 8. 统计与查找 count / index ==============================
# 【讲解】
# .count(a)  : 统计 a 在序列里出现了几次
# .index(a)  : 查 a 第一次出现的位置(下标)
# 注意:
#   index 找不到会直接报错 ValueError
#   字符串额外有个 .find(a),找不到返回 -1 不报错（find 只有字符串有!）
print("\n=== 8. count 统计 / index 查位置 ===")
nums = [1, 2, 2, 3, 2]
print(f"原始: {nums}")
print("操作: .count(2)   2出现了几次")
print(f"结果: {nums.count(2)}")
print("操作: .index(3)   3第一次出现的下标")
print(f"结果: {nums.index(3)}")
print("⚠️ index 找不到会报错;字符串还有 find,找不到返回 -1")


# ============================== 9. sorted() 排序 ==============================
# 【讲解】
# sorted(x)          : 升序排序
# sorted(x, reverse=True) : 降序排序
# 注意:
#   sorted 对任何序列都能用,但返回的是【新列表】
#   原字符串/元组/列表不会被修改
#   （列表自己的 .sort() 是原地排序,只属于列表,不是通用操作）
print("\n=== 9. sorted() 排序 ===")
print(f"原始: tup1 = {tup1}")
print("操作: sorted(tup1, reverse=True)  降序")
print(f"结果1: {sorted(tup1, reverse=True)}")
print(f"结果2: {sorted(tup1)}")
print("提示: sorted() 返回的是新列表,原数据不变")
print(f"验证: 原元组还是 {tup1}")


# ---------- 小抄：一眼对照表 ----------
# 通用操作          |  写法             |  说明
# -----------------|------------------|------------------------
# 下标取值          |  x[0] / x[-1]    |  正数从0起，负数从-1起
# 切片              |  x[1:4]          |  含头不含尾
# 切片+步长         |  x[::2]          |  每隔1个取1个
# 反转              |  x[::-1]         |  步长-1
# 拼接              |  x1 + x2         |  同类型才能拼
# 重复              |  x * 3           |  重复3次
# 成员判断          |  a in x          |  在返回 True
# 长度              |  len(x)          |  元素个数
# 最大/最小         |  max(x) / min(x) |  元素需可比较
# 求和              |  sum(x)          |  仅数字序列
# 遍历              |  for a in x      |  逐个取出
# 统计次数          |  x.count(a)      |  a 出现几次
# 查位置            |  x.index(a)      |  a 第一次出现的下标(找不到报错)
# 排序(新列表)      |  sorted(x)       |  任何序列可用,返回新列表
