# ==================== 转义字符（可视化对比版） ====================
# 每个例子都按：原始/想显示 → 操作 → 结果 展示
# 记住：反斜杠 \ 的意思 = "下一个字符当普通字符显示，别当成语法符号"


# ---------- 1. \n 换行 ----------
print("=== 1. \\n 换行 ===")
s = "你好\n世界"
print(f"原始: '你好\\n世界'（中间有\\n）")
print("操作: print(s)")
print(f"结果:")
print(s)
print("对比: 不加\\n → 你好世界（挤一行）；加\\n → 分两行")


# ---------- 2. \t 制表符 ----------
print("\n=== 2. \\t 制表符 ===")
s = "姓名\t年龄\t性别"
print(f"原始: '姓名\\t年龄\\t性别'（中间有\\t）")
print("操作: print(s)")
print(f"结果: {s}")
print("对比: 不加\\t → 姓名年龄性别（挤一起）；加\\t → 自动空开对齐")


# ---------- 3. \" 双引号 ----------
print("\n=== 3. \\\" 双引号 ===")
print('想显示: 他说："你好"')
print("❌ 错误写法: 直接把双引号嵌在双引号字符串里 → 引号配对混乱，报错！")
s = "他说：\"你好\""
print("✅ 操作: 外层用双引号，内层引号前加 \\  →  \"他说：\\\"你好\\\"\"")
print(f"结果: {s}")


# ---------- 4. \' 单引号 ----------
print("\n=== 4. \\' 单引号 ===")
print("想显示: It's a pen")
print("❌ 错误写法: print('It's a pen')  中间的'把字符串提前结束，报错！")
s = 'It\'s a pen'
print("✅ 操作: 中间的 ' 前加 \\  →  'It\\'s a pen'")
print(f"结果: {s}")


# ---------- 5. \\ 反斜杠 ----------
print("\n=== 5. \\\\ 反斜杠 ===")
print("想显示: 路径 D:\\new\\test")
print("❌ 错误写法: print(\"D:\\new\\test\")  \\n 被当成换行，路径乱掉")
s = "D:\\new\\test"
print("✅ 操作: 每个 \\ 都写成 \\  →  \"D:\\\\new\\\\test\"")
print(f"结果: {s}")
print("⚠️ 记住: Windows 文件路径必须用 \\\\")


# ---------- 综合例子 ----------
print("\n=== 综合例子: 打印表格 ===")
print("操作: \\t 对齐列 + \\n 换行")
print("代码: print(\"姓名\\t年龄\\t班级\") + print(\"张三\\t18\\t一班\\n李四\\t19\\t二班\")")
print("结果:")
print("姓名\t年龄\t班级")
print("张三\t18\t一班\n李四\t19\t二班")


# ---------- 小抄：一眼对照表 ----------
# 转义符  |  作用        |  代码写法              |  输出
# --------|-------------|----------------------|----------
#   \n    |  换行        |  "第一行\n第二行"      |  分两行
#   \t    |  空一格(Tab) |  "姓名\t年龄"          |  姓名    年龄
#   \"    |  显示双引号  |  "他说\"你好\""        |  他说"你好"
#   \'    |  显示单引号  |  'It\'s ok'           |  It's ok
#   \\    |  显示反斜杠  |  "D:\\python"         |  D:\python
